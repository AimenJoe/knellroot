//! 도트 픽토그램 그리기와 패시브 칸의 그림(0161 — KB `meta-progression-unlock-planning` "칸마다 그림").
//!
//! 그림은 13×13 칸(`#` = 칠한 칸)이고 터치 버튼의 것(`touch::icon_mask`, 0146)과 같은 방법으로 찍는다: 밝은 몸 + 어두운 한 칸 테,
//! 칸은 정수 px. 스킬·큰 기술의 그림은 터치 버튼의 것을 그대로 쓰고(`touch::skill_icon`·`ult_icon`), 패시브 15칸의 그림만 여기 있다 —
//! 둥근 칸 안에 서도록 모서리를 비워 그린다(시험). 새 패시브 칸 = 그림 하나(`_` 없는 match) + 시험이 구별을 본다.
use macroquad::prelude::*;

use crate::progression::Cell;

/// 픽토그램의 한 변(칸) — 터치 버튼의 것과 같다.
pub const N: usize = 13;

pub type Mask = [&'static str; N];

/// 그림의 칸 `(x, y)`가 칠해졌나.
pub fn on(mask: &Mask, x: usize, y: usize) -> bool {
    x < N && y < N && mask[y].as_bytes()[x] == b'#'
}

/// 픽토그램 찍기: 가운데 `c`, 한 칸 `px`(화면 px — 정수로 준다). 어두운 한 칸 테(`edge`) 위에 몸(`body`).
/// 테는 칠한 칸의 이웃 여덟 칸 가운데 빈 칸을 한 번씩만(겹쳐 그리면 반투명이 얼룩진다).
pub fn draw(cell: impl Fn(usize, usize) -> bool, c: Vec2, px: f32, body: Color, edge: Color) {
    let size = N as f32 * px;
    let (x0, y0) = ((c.x - size / 2.0).round(), (c.y - size / 2.0).round());
    let n = N as i32;
    if edge.a > 0.0 {
        for y in -1..=n {
            for x in -1..=n {
                let at = |dx: i32, dy: i32| {
                    let (u, v) = (x + dx, y + dy);
                    u >= 0 && v >= 0 && cell(u as usize, v as usize)
                };
                if at(0, 0) {
                    continue;
                }
                if (-1..=1).any(|dy| (-1..=1).any(|dx| at(dx, dy))) {
                    draw_rectangle(x0 + x as f32 * px, y0 + y as f32 * px, px, px, edge);
                }
            }
        }
    }
    for y in 0..N {
        for x in 0..N {
            if cell(x, y) {
                draw_rectangle(x0 + x as f32 * px, y0 + y as f32 * px, px, px, body);
            }
        }
    }
}

