#[cfg(test)]
mod tests {
    use super::*;
    use crate::progression::TREE;
    use crate::touch;

    fn grid(m: &Mask) -> Vec<bool> {
        (0..N * N).map(|i| on(m, i % N, i / N)).collect()
    }

    /// 0161: 패시브 15칸마다 그림 하나 — 13×13, `#`·`.`만, 칸이 너무 적지도(안 보임) 꽉 차지도(덩어리) 않고, 둥근 칸 안에 서게
    /// 모서리가 비어 있다. 서로, 그리고 터치 버튼의 모든 그림(스킬·큰 기술 포함)과 12칸 이상 다르다 — 같은 판에 나란히 서도 갈린다.
    #[test]
    fn passive_cells_each_have_a_round_13_by_13_picture_unlike_any_other() {
        let cells: Vec<Cell> = TREE.iter().flat_map(|r| r.iter().map(|d| d.cell)).collect();
        assert_eq!(cells.len(), 15);
        assert_eq!(N, touch::ICON_N, "one grid for every pictogram");
        let masks: Vec<(String, Vec<bool>)> = cells
            .iter()
            .map(|c| {
                let m = cell_mask(*c);
                for row in m {
                    assert_eq!(row.len(), N, "{c:?}: {row}");
                    assert!(row.bytes().all(|b| b == b'#' || b == b'.'), "{c:?}");
                }
                let g = grid(&m);
                let n = g.iter().filter(|x| **x).count();
                assert!((24..=100).contains(&n), "{c:?}: {n} cells");
                // 둥근 칸: 가운데(6, 6)에서 반지름 6.7칸 안.
                for (i, on) in g.iter().enumerate() {
                    let (dx, dy) = ((i % N) as i32 - 6, (i / N) as i32 - 6);
                    assert!(
                        !on || dx * dx + dy * dy <= 45,
                        "{c:?}: ({}, {}) pokes out of the round cell",
                        i % N,
                        i / N
                    );
                }
                (format!("{c:?}"), g)
            })
            .collect();
        let touch_kinds = [
            touch::Kind::Attack,
            touch::Kind::Dodge,
            touch::Kind::Parry,
            touch::Kind::Jump,
            touch::Kind::Flask,
            touch::Kind::Cast,
            touch::Kind::Rest,
            touch::Kind::Lock,
            touch::Kind::TurnLeft,
            touch::Kind::TurnRight,
            touch::Kind::Pause,
            touch::Kind::Hammer,
            touch::Kind::Staff,
            touch::Kind::Crossbow,
            touch::Kind::Fist,
            touch::Kind::Whirl,
            touch::Kind::Cut,
            touch::Kind::Gather,
            touch::Kind::Quake,
            touch::Kind::Upend,
            touch::Kind::Brace,
            touch::Kind::Echo,
            touch::Kind::Throw,
            touch::Kind::Embers,
            touch::Kind::Flurry,
            touch::Kind::Line,
            touch::Kind::Bomb,
        ];
        let others: Vec<(String, Vec<bool>)> = touch_kinds
            .iter()
            .map(|k| {
                let g = (0..N * N)
                    .map(|i| touch::icon_cell(*k, i % N, i / N))
                    .collect();
                (format!("{k:?}"), g)
            })
            .collect();
        let apart = |a: &[bool], b: &[bool]| a.iter().zip(b).filter(|(x, y)| x != y).count();
        for (i, (a, ga)) in masks.iter().enumerate() {
            for (b, gb) in masks[i + 1..].iter().chain(&others) {
                let d = apart(ga, gb);
                assert!(d >= 12, "{a} and {b} look alike ({d} cells apart)");
            }
        }
        assert!(!on(&cell_mask(Cell::Catch), N, 0) && !on(&cell_mask(Cell::Catch), 0, N));
    }
}
