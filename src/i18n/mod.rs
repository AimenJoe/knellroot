/// 표 밖에서 화면에 찍는 기호(메뉴 표지 등). 글꼴 시험이 같이 본다.
pub const UI_GLYPHS: &str = "◆◇…·▲▼▶◀→";

/// 아이템 옵션 한 줄의 글(0223 V4 — "주는 피해 +4" · "자세 피해 +14%" · "스킬 대기 −7%").
pub fn affix_line(a: &crate::items::Affix) -> String {
    use crate::items::Stat;
    let s = s();
    let name = match a.stat {
        Stat::Dmg => s.affix_dmg,
        Stat::Heavy => s.affix_heavy,
        Stat::Shot => s.affix_shot,
        Stat::Poise => s.affix_poise,
        Stat::Swift => s.affix_swift,
        Stat::Opened => s.affix_opened,
        Stat::Stamina => s.affix_stamina,
        Stat::Regen => s.affix_regen,
        Stat::KillStamina => s.affix_kill,
        Stat::Ember => s.affix_ember,
        Stat::Hp => s.affix_hp,
        Stat::Cooldown => s.affix_cd,
        Stat::Build => s.affix_build,
    };
    let v = (a.stat.value(a.tier).round() as i32).to_string();
    let form = match (a.stat, a.stat.percent()) {
        (Stat::Cooldown, _) => s.affix_minus_pct,
        (_, true) => s.affix_plus_pct,
        (_, false) => s.affix_plus,
    };
    fill(form, &[name, &v])
}

/// 아이템의 이름: 등급이 있으면 "단단한 낡은 검", 보통이면 바탕 이름 그대로.
pub fn item_label(rarity: crate::items::Rarity, base_name: &str) -> String {
    match rarity_word(rarity) {
        None => base_name.to_string(),
        Some(word) => fill(s().item_label, &[word, base_name]),
    }
}

/// 등급의 말(보통은 없다) — 큰 창의 머리·후보 줄은 이름과 따로 쓴다(0275: 이름 칸이 "고급 종치기 망치"로 넘쳤다).
pub fn rarity_word(rarity: crate::items::Rarity) -> Option<&'static str> {
    use crate::items::Rarity;
    let s = s();
    match rarity {
        Rarity::Plain => None,
        Rarity::Sturdy => Some(s.rarity_sturdy),
        Rarity::Rare => Some(s.rarity_rare),
        Rarity::Unique => Some(s.rarity_unique),
    }
}

/// 갈래 줄 앞에 등급(0275): "고급 · 주무기" — 보통이면 갈래 그대로.
pub fn with_rarity(rarity: Option<crate::items::Rarity>, kind: &str) -> String {
    match rarity.and_then(rarity_word) {
        Some(word) => format!("{word} · {kind}"),
        None => kind.to_string(),
    }
}

/// 피해 타입의 이름(0223 V2 — 물리는 이름이 없다).
pub fn ail_name(k: crate::status::Kind) -> &'static str {
    use crate::status::Kind;
    let s = s();
    match k {
        Kind::Physical => "",
        Kind::Ember => s.ail_ember,
        Kind::Root => s.ail_root,
        Kind::Knell => s.ail_knell,
        Kind::Rift => s.ail_rift,
        Kind::Shock => s.ail_shock,
        Kind::Sharp => s.ail_sharp,
        Kind::Frost => s.ail_frost,
        Kind::Drain => s.ail_drain,
    }
}

/// 피해 타입의 풀이(기술 탭 — 무엇이 쌓이고, 차면 어떻게 되나).
pub fn ail_desc(k: crate::status::Kind) -> &'static str {
    use crate::status::Kind;
    let s = s();
    match k {
        Kind::Physical => "",
        Kind::Ember => s.ail_ember_d,
        Kind::Root => s.ail_root_d,
        Kind::Knell => s.ail_knell_d,
        Kind::Rift => s.ail_rift_d,
        Kind::Shock => s.ail_shock_d,
        Kind::Sharp => s.ail_sharp_d,
        Kind::Frost => s.ail_frost_d,
        Kind::Drain => s.ail_drain_d,
    }
}

/// 종의 타입 배율 → (잘 듣는 타입 이름들, 덜 듣는 타입 이름들) — " · "로 이은 글(도감).
pub fn ail_leanings(mult: &[f32; crate::status::N]) -> (String, String) {
    let pick = |want: fn(f32) -> bool| {
        crate::status::TYPED
            .iter()
            .zip(mult)
            .filter(|(_, m)| want(**m))
            .map(|(k, _)| ail_name(*k))
            .collect::<Vec<_>>()
            .join(" · ")
    };
    (pick(|m| m > 1.0), pick(|m| m < 1.0))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 모든 언어의 모든 글자가 글꼴에 있다(없으면 빈 칸으로 찍힌다).
    #[test]
    fn every_string_is_drawable_with_the_font() {
        for font in [
            &include_bytes!("../../assets/fonts/GowunBatang-UI-Regular.ttf")[..],
            include_bytes!("../../assets/fonts/GowunBatang-UI-Bold.ttf"),
        ] {
            let face = ttf_parser::Face::parse(font, 0).unwrap();
            for l in Lang::ALL {
                // 개발 화면 글(0080)도 같은 글꼴로 그린다.
                let dev_texts = dev_texts();
                for text in all(l.strings())
                    .into_iter()
                    .chain([UI_GLYPHS])
                    .chain(dev_texts)
                {
                    for c in text.chars() {
                        assert!(
                        c.is_whitespace() || face.glyph_index(c).is_some(),
                        "{l:?}: {c:?} in {text:?} not in the UI font — tools/fonts/subset_ui.py"
                    );
                    }
                }
            }
        }
    }

    /// 자리표시자({0}…)가 언어끼리 같다.
    #[test]
    fn placeholders_match_across_languages() {
        let count = |t: &str| (0..4).filter(|i| t.contains(&format!("{{{i}}}"))).count();
        let ko = all(&KO);
        for l in Lang::ALL {
            for (a, b) in ko.iter().zip(all(l.strings())) {
                assert_eq!(count(a), count(b), "{l:?}: {b:?}");
            }
        }
        assert_eq!(fill("{0} · {1}", &["a", "b"]), "a · b");
    }
}
