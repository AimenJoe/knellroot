//!
//! - 플레이어가 보는 글은 전부 언어별 표(`ko.rs`·`en.rs`) 한 곳에. 키는 `Strings`의 필드 — 한 언어에 빠지면 컴파일이 안 된다.
//! - 숫자가 들어가는 글은 `{0}`·`{1}` + `fill()`. 문장을 조각으로 잇지 않는다.
//! - 데이터 표(스테이지·적·구역)는 글 대신 `Tr`(표에서 글을 고르는 함수)을 들고, 그릴 때 `tr()`로 꺼낸다. 월드는 언어를 모른다.
//! - 키 이름(J·Space·X …)은 글에 박지 않는다 — 동사만 여기, 키 그림은 `input::prompt`가 지금 장치에 맞춰 붙인다.
//! - 글꼴은 고운바탕(OFL) 서브셋 — 표 글자만 들어 있다(0021). 새 글자를 쓰면 `tools/fonts/subset_ui.py`를 다시 돌린다(시험이 잡는다).
//! - 지금 두 언어(한국어·영어). 구조는 첫 게임처럼 열한 언어까지 그대로 늘어난다(파일 하나 + `Lang` 한 줄).
use std::sync::atomic::{AtomicU8, Ordering};

#[cfg(feature = "dev")]
pub mod dev;
mod en;
mod ko;

pub use en::EN;
pub use ko::KO;

/// 표에서 글 하나를 고르는 함수.
pub type Tr = fn(&Strings) -> &'static str;

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    Ko,
    En,
}

impl Lang {
    pub const ALL: [Lang; 2] = [Lang::Ko, Lang::En];

    pub fn strings(self) -> &'static Strings {
        match self {
            Lang::Ko => &KO,
            Lang::En => &EN,
        }
    }

    pub fn next(self) -> Lang {
        let i = Lang::ALL.iter().position(|l| *l == self).unwrap_or(0);
        Lang::ALL[(i + 1) % Lang::ALL.len()]
    }
}

#[cfg(not(test))]
static LANG: AtomicU8 = AtomicU8::new(0);
// 시험(0275): 언어는 시험 스레드마다 — 영어로 재는 시험이 같은 때 도는 다른 시험의 한국어를 바꾸지 않게.
#[cfg(test)]
thread_local! {
    static LANG: AtomicU8 = const { AtomicU8::new(0) };
}

fn lang_index() -> u8 {
    #[cfg(not(test))]
    return LANG.load(Ordering::Relaxed);
    #[cfg(test)]
    LANG.with(|l| l.load(Ordering::Relaxed))
}

pub fn lang() -> Lang {
    Lang::ALL[lang_index() as usize % Lang::ALL.len()]
}

pub fn set_lang(l: Lang) {
    let i = Lang::ALL.iter().position(|x| *x == l).unwrap_or(0) as u8;
    #[cfg(not(test))]
    LANG.store(i, Ordering::Relaxed);
    #[cfg(test)]
    LANG.with(|x| x.store(i, Ordering::Relaxed));
}

/// 지금 언어의 표.
pub fn s() -> &'static Strings {
    lang().strings()
}

pub fn tr(f: Tr) -> &'static str {
    f(s())
}

/// `{0}`, `{1}` … 자리에 값을 채운다.
pub fn fill(template: &str, args: &[&str]) -> String {
    let mut out = template.to_string();
    for (i, a) in args.iter().enumerate() {
        out = out.replace(&format!("{{{i}}}"), a);
    }
    out
}

